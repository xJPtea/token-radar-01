// Token Launch Radar, model radar-2: one snapshot in, one ranked board out.
//
// The board ranks pre-token protocols only: a protocol is pre-token when its DefiLlama record
// carries no token (mcap_usd, gecko_id and symbol all null). Protocols whose token already trades
// are kept apart in the Live view with their market cap, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures, never from a name:
//
//   base      = tvl_usd x 0.18
//   growth    = clamp(change_7d, -50, 150) per cent
//   growthMult = 1 + growth/100 x 0.60 when growth >= 0, else 1 + growth/100 x 0.90
//                (a falling TVL is punished harder than a rising one is rewarded)
//   maturity  = 0.55 + 0.45 x ln(1 + age_days) / ln(1 + 1460)
//                (log age: a protocol that ran years with no token has banked more
//                 unpriced usage than one listed last month; age unknown: 365 days)
//   breadth   = 1 + 0.03 x min(chains - 1, 5)   (each extra chain adds surface to farm)
//   sector    = a small multiple by category family, 0.90 .. 1.10
//   implied   = max(1, round(base x growthMult x maturity x breadth x sector))
//
// Every constant is stated in the dashboard's model panel and in MODEL. The same function scores
// every row; no protocol name is ever special-cased. Deterministic: age is counted from the
// snapshot's as_of date, so two runs write the same bytes.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_up_weight: number;
  growth_down_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.18,
  growth_up_weight: 0.6,
  growth_down_weight: 0.9,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_per_chain: 0.03,
  breadth_max_chains: 5,
};

